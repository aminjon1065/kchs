@dataclass
class Place:
    code: str | None
    level: str | None
    note: str  # пусто — уверенно; иначе — почему привязка приблизительная или её нет


class Gazetteer:
    """Название района или области из таблицы → код справочника территорий."""

    def __init__(self, territories: dict[str, Territory]):
        self.t = territories
        self.districts: dict[str, str] = {}
        for code, item in territories.items():
            if item.level == "district":
                for name in (item.ru, item.tg):
                    self.districts[flat(name)] = code
        for code, names in RENAMED_NAMES.items():
            for name in names:
                self.districts[flat(PREFIX.sub("", name))] = code
        self.regions = {flat(alias): code for code, aliases in REGIONS.items() for alias in aliases}

    def _one_district(self, raw: str, year: int | None) -> str | None:
        name = PREFIX.sub("", clean(raw)).strip(" .,:;")
        name = SUFFIX.sub("", name).strip(" .,:;")
        key = flat(name)
        if not key:
            return None
        if key in ("бахтар", "бахтарскии"):
            # До 2018 года — Бохтарский район (ныне Кушониён), после — город Бохтар
            return "TJ-KT-14" if (year or 0) < 2018 else "TJ-KT-01"
        if key.startswith("курган"):
            return "TJ-KT-01"  # Курган-Тюбе — ныне город Бохтар
        if key in self.districts:
            return self.districts[key]
        for known, code in self.districts.items():
            if len(known) >= 4 and (key.startswith(known) or known.startswith(key)) and len(key) >= 4:
                return code
        close = difflib.get_close_matches(key, list(self.districts), n=1, cutoff=0.86)
        return self.districts[close[0]] if close else None

    def region(self, raw: str) -> str | None:
        full = flat(raw)
        if full in self.regions:
            return self.regions[full]
        key = flat(PREFIX.sub("", clean(raw)))
        if key in self.regions:
            return self.regions[key]
        for alias, code in self.regions.items():
            if len(alias) >= 4 and key.startswith(alias):
                return code
        return None

    def place(self, province: str, district: str, year: int | None) -> Place:
        district = clean(district)
        region = self.region(province) if province else None
        parts = [p for p in re.split(r"[,;/]| и ", district) if p.strip()] if district else []
        codes = [c for c in (self._one_district(p, year) for p in parts) if c]
        if codes:
            code = codes[0]
            note = "несколько районов: привязан первый" if len(set(codes)) > 1 else ""
            parent = self.t[code].parent
            if region and region not in (parent, "TJ") and not note:
                note = f"район из другой области ({province})"
            return Place(code, "district", note)
        # Район не узнан или не указан: область, если она есть
        as_region = self.region(district) if district else None
        if as_region:
            return Place(as_region, self.t[as_region].level, "")
        if region:
            return Place(region, self.t[region].level, f"район не распознан: «{district}»" if district else "указана только область")
        abroad = flat(f"{province} {district}")
        if re.search(r"россия|русия|федератс|москва|казакистан|казахстан|киргизистан|кыргыз|пакистан|^фр|^чк|санкт", abroad):
            return Place("TJ", "country", "за пределами РТ")
        # Поле территории в реестре обязательно: без места — вся республика, с замечанием
        if not province and not district:
            return Place("TJ", "country", "место не указано")
        return Place("TJ", "country", f"не распознано: «{province} / {district}»")


