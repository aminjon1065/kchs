def load_territories(path: str | Path = "/seed/territories.json") -> dict[str, Territory]:
    """Справочник территорий платформы — сид `apps/api/src/seed/territories.json`."""
    items = json.loads(Path(path).read_text(encoding="utf-8"))
    return {
        item["code"]: Territory(item["code"], item["level"], item["name"]["ru"], item["name"].get("tg", ""), item["parent"] or "")
        for item in items
    }


