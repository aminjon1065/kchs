# Старые таджикские шрифты набирали ҳ, ӣ, ғ, қ, ҷ, ӯ сербскими и македонскими буквами
LEGACY = str.maketrans("њЊїЇѓЃќЌљЉўЎ", "ҳҲӣӢғҒқҚҷҶӯӮ")
# Для сравнения названий: таджикские буквы — к русским, гласные а/о и е/ё — к одной
FLAT = str.maketrans({"ҳ": "х", "ӣ": "и", "ғ": "г", "қ": "к", "ҷ": "ч", "ӯ": "у", "ё": "е",
                      "ъ": "", "ь": "", "й": "и", "о": "а", "я": "а", "э": "е", "ы": "и"})


def clean(value: object) -> str:
    """Текст ячейки: старые буквы → таджикские, пробелы схлопнуты."""
    if value is None:
        return ""
    text = str(value).translate(LEGACY)
    return re.sub(r"[ \t\r\f\v]+", " ", text).replace(" \n", "\n").strip()


def flat(value: str) -> str:
    """Скелет названия для сравнения: нижний регистр, русские буквы, «дж» = «ч»."""
    text = clean(value).lower().translate(FLAT)
    text = text.replace("дж", "ч").replace("ш", "ш")
    return re.sub(r"[^а-яa-z]", "", text)


def number(value: object) -> float | None:
    """Число из ячейки: «1 234,5», «12.0» → 1234.5, 12.0; текст без числа — None."""
    if value is None:
        return None
    if isinstance(value, (int, float)):
        return float(value)
    text = clean(value).replace(" ", " ")
    match = re.fullmatch(r"\s*(-?\d[\d ]*(?:[.,]\d+)?)\s*", text)
    if not match:
        return None
    return float(match.group(1).replace(" ", "").replace(",", "."))


def integer(value: object) -> int | None:
    n = number(value)
    return int(n) if n is not None and n == int(n) and n >= 0 else None


