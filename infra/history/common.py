def classify(raw: str, description: str = "") -> tuple[str, str]:
    """Вид в источнике → (код классификатора, как определён: «вид»/«описание»/«нет»)."""
    text = clean(raw).lower()
    for code, pattern in RULES:
        if text and re.search(pattern, text):
            return code, "вид"
    desc = clean(description).lower()[:300]
    for code, pattern in RULES:
        if desc and re.search(pattern, desc):
            return code, "описание"
    return "OTHER", "нет"
