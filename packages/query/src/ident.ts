/**
 * Имя в двойных кавычках — единственный помощник экранирования идентификаторов
 * (ADR-0184): компилятор и SQL-лаборатория здесь, физические таблицы датасетов,
 * обёртки тайлов и внешние базы в api. Удвоенная кавычка — экранирование: так
 * читают имена Postgres, DuckDB и язык выражений. Проверка имени по своим
 * правилам (сгенерированное, ключ поля) — у вызывающего, кавычки — защита в глубину.
 */
export function quoteIdent(name: string): string {
  return `"${name.replaceAll('"', '""')}"`
}
