-- Человеческий порядок строк (ADR-0229): база создана с C.UTF-8, и списки шли по байтам —
-- «Ёров» перед «Абдуллоевым», «Ғафуров» и «Ҷураев» после «Я», «10» перед «2». ICU-коллация
-- таджикского языка с числами по значению: Ғ после Г, Қ после К, Ӯ после У, Ҷ после Ч, Ё —
-- рядом с Е. Порядок задаётся в ORDER BY (`natural()` в shared/db/collation.ts): столбцы
-- входят в представления системных датасетов, и смена их коллации потребовала бы пересоздать
-- представления. Равенство не меняется — коллация детерминированная.
CREATE COLLATION IF NOT EXISTS "kchs_natural" (provider = icu, locale = 'tg-u-kn');
