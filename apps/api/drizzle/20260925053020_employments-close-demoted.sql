-- Перевод сотрудника из консоли раньше не закрывал прежнее основное назначение, а делал
-- его неосновным: сотрудник сохранял доступ к данным прежнего подразделения (множество
-- принципалов берёт все действующие занятости). Совместительства платформа не заводит
-- ни одним путём, поэтому каждая действующая неосновная занятость — след такого
-- перевода или снятия с подразделения: закрываем её датой, история остаётся.
-- Кэш принципалов (5 минут) догонит сам.
UPDATE "employments"
   SET "ends_at" = current_date
 WHERE NOT "is_primary"
   AND "ends_at" IS NULL;
