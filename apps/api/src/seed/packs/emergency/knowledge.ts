async function publish(ownerId: string, pageId: string): Promise<boolean> {
  const ctx = await buildUserCtxFor(ownerId)
  if (!ctx) return false
  try {
    await PageService.publish(ctx, pageId, { note: 'Первая редакция пакета ЧС' })
    return true
  } catch {
    // Нет сервера совместной правки — страница остаётся черновиком (как у сида руководства)
    return false
  }
}

export async function ensureKnowledge(pack: PackContext): Promise<number> {
  let rootId = await findPackObject('page', 'page.root')
  if (!rootId) {
    rootId = await db().transaction(async (tx) => {
      const id = await PageService.create(
        tx,
        pack.ctx,
        { title: 'Регламенты штаба ЧС', spaceId: pack.spaceId, template: 'regulation' },
        'ru',
      )
      await markPackObject(tx, pack.ctx, id, 'page.root')
      return id
    })
  }
  let created = 0
  let published = 0
  for (const page of PAGES) {
    if (await findPackObject('page', page.key)) continue
    const parentId = rootId
    const id = await db().transaction(async (tx) => {
      const pageId = await PageService.create(
        tx,
        pack.ctx,
        {
          title: page.title,
          spaceId: pack.spaceId,
          parentId,
          template: 'blank',
          blocks: page.blocks.map(
            (item, index) => ({ ...item, id: `em-${index + 1}` }) as PageBlock,
          ),
        },
        'ru',
      )
      await markPackObject(tx, pack.ctx, pageId, page.key)
      return pageId
    })
    created += 1
    if (await publish(pack.adminId, id)) published += 1
  }
  pack.log('регламенты штаба в базе знаний', { created, published })
  return created
}
