import { describe, expect, it } from 'vitest'
import { parseDate, parseRequisites } from './parse.js'

/** Реквизиты письма из госЭДО (ADR-0219): номер, дата, отправитель, тема из текста бланка. */
describe('реквизиты из текста документа госЭДО', () => {
  it('русский бланк: ведомство, номер с датой в одной строке, тема в две строки', () => {
    const text = [
      'МИНИСТЕРСТВО ФИНАНСОВ',
      'РЕСПУБЛИКИ ТАДЖИКИСТАН',
      'г. Душанбе, пр. Академиков Раджабовых, 3',
      'Исх. № 12-3/456 от 05.03.2026',
      'Председателю Комитета по чрезвычайным ситуациям',
      'О выделении средств на ликвидацию',
      'последствий паводка в Варзобском районе',
      'Уважаемый ...',
    ].join('\n')
    expect(parseRequisites(text)).toEqual({
      externalNumber: '12-3/456',
      externalDate: '2026-03-05',
      sender: 'МИНИСТЕРСТВО ФИНАНСОВ',
      subject: 'О выделении средств на ликвидацию последствий паводка в Варзобском районе',
    })
  })

  it('таджикский бланк: «рақами», дата словами, «Оид ба»', () => {
    const text = [
      'ВАЗОРАТИ КОРҲОИ ДОХИЛИИ ҶУМҲУРИИ ТОҶИКИСТОН',
      'рақами 7/88',
      '«14» октябри 2026',
      'Оид ба ҳамкорӣ ҳангоми обхезӣ',
    ].join('\n')
    expect(parseRequisites(text)).toMatchObject({
      externalNumber: '7/88',
      externalDate: '2026-10-14',
      sender: 'ВАЗОРАТИ КОРҲОИ ДОХИЛИИ ҶУМҲУРИИ ТОҶИКИСТОН',
      subject: 'Оид ба ҳамкорӣ ҳангоми обхезӣ',
    })
  })

  it('ничего не нашлось — пусто, а не догадка', () => {
    expect(parseRequisites('Просто текст без реквизитов\nи без темы')).toEqual({
      externalNumber: null,
      externalDate: null,
      sender: null,
      subject: null,
    })
  })

  it('даты: числовая, словами, ISO; невозможная дата — null', () => {
    expect(parseDate('от 01.02.2026')).toBe('2026-02-01')
    expect(parseDate('«3» марта 2025 г.')).toBe('2025-03-03')
    expect(parseDate('2026-10-14')).toBe('2026-10-14')
    expect(parseDate('31.02.2026')).toBeNull()
  })
})
