@dataclass(frozen=True)
class IncidentKind:
    code: str
    name: str
    group: str
    # Доля в общем числе происшествий (до сезонности)
    share: float
    # Сезонность: множитель интенсивности по месяцам, январь…декабрь
    season: tuple[float, ...]
    # Вес района: население ** population_power × горность ** mountain_power
    population_power: float
    mountain_power: float
    hours: str
    # Как далеко от населённого пункта, км (сели и лавины — в ущельях и на дорогах)
    spread_km: float
    damage_median: float
    damage_sigma: float
    # Доля происшествий с оценённым ущербом (остальные — пусто)
    damage_known: float
    injured_chance: float
    injured_mean: float
    # Если пострадавшие есть, то не меньше (заболевшие при вспышке — от двух)
    injured_min: int
    deaths_chance: float
    deaths_mean: float
    templates: tuple[str, ...]


